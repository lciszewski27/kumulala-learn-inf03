import { chromium } from 'playwright';
import path from 'node:path';
const root = process.cwd();
const browser = await chromium.launch({headless:true});
const page = await browser.newPage();
await page.goto('file://' + path.join(root,'src/test.html'), {waitUntil:'load'});
await page.evaluate(async()=>{await document.fonts.ready; if(window.Prism) Prism.highlightAll(); await document.fonts.ready;});
await page.waitForTimeout(200);
await page.pdf({path: path.join(root,'.build/test.pdf'), format:'A4', printBackground:true, margin:{top:'17mm',right:'13mm',bottom:'15mm',left:'13mm'}, displayHeaderFooter:true, headerTemplate:`<div style="width:100%;font-family:sans-serif;font-size:7pt;color:#7e22ce;padding:0 13mm;display:flex;justify-content:space-between;"><span>kumulala learn ♡ · egzamin inf.03</span><span>ściąga tematyczna</span></div>`, footerTemplate:`<div style="width:100%;font-family:sans-serif;font-size:7pt;color:#7e22ce;padding:0 13mm;display:flex;justify-content:space-between;"><span>materiał do nauki</span><span>str. <span class="pageNumber"></span> / <span class="totalPages"></span></span></div>`, outline:true, tagged:true});
await browser.close();
